"""Scripted walkthrough runner — scripts/run_walkthrough.py

Reads docs/user_test/walkthrough_inputs.json, pipes each input through the
same run_session() function the Streamlit app uses (no logic copied), forces
offline mode (watsonx.ai disabled), and reports results.

Output is saved to docs/user_test/walkthrough_output.md and a summary table
is printed to stdout.

Usage:
    python scripts/run_walkthrough.py
"""

from __future__ import annotations

import json
import os
import sys
import time
from pathlib import Path

# ── Force offline mode ────────────────────────────────────────────────────────
for _k in ("WATSONX_API_KEY", "WATSONX_URL", "WATSONX_PROJECT_ID"):
    os.environ.pop(_k, None)

# ── Path setup (run from project root) ───────────────────────────────────────
_ROOT = Path(__file__).parent.parent
sys.path.insert(0, str(_ROOT))

from src.checks import _check_banned_phrases          # noqa: E402
from src.orchestrator import run_session               # noqa: E402


# ── Constants ─────────────────────────────────────────────────────────────────
_INPUTS_PATH = _ROOT / "docs" / "user_test" / "walkthrough_inputs.json"
_OUTPUT_PATH  = _ROOT / "docs" / "user_test" / "walkthrough_output.md"

_TIER_ICON = {"emergency": "🔴", "urgent": "🟠", "routine": "🟢"}


# ── Helpers ───────────────────────────────────────────────────────────────────

def _flags(inp: dict, result) -> list[str]:
    """Return a list of human-readable flag strings for one result."""
    problems: list[str] = []

    # Tier mismatch (only when expected_tier is not null)
    expected = inp.get("expected_tier")
    if expected is not None and result.tier != expected:
        problems.append(
            f"TIER MISMATCH: expected {expected!r}, got {result.tier!r}"
        )

    # Banned phrases in answer
    banned_hits = _check_banned_phrases(result.answer_text)
    for bh in banned_hits:
        problems.append(f"BANNED PHRASE: {bh}")

    # Any ranked option missing a last_verified date
    for r in result.ranked:
        svc = r.service
        if not getattr(svc, "last_verified", None):
            problems.append(
                f"NO LAST_VERIFIED: {svc.name} ({svc.id})"
            )

    return problems


def _format_options(result) -> list[str]:
    """Return one display line per ranked result."""
    lines: list[str] = []
    for r in result.ranked:
        svc = r.service
        dist = (
            f"{svc.distance_km:.1f} km (~{svc.travel_min_estimate:.0f} min)"
            if svc.distance_km is not None
            else "online (no travel)"
        )
        fallback_tag = " [fallback]" if r.is_fallback else f" score={r.score:.3f}"
        lines.append(
            f"  #{r.rank}{fallback_tag}  {svc.name} ({svc.id})"
            f"  dist={dist}"
            f"  verified={svc.last_verified or 'MISSING'}"
        )
    return lines


# ── Main ──────────────────────────────────────────────────────────────────────

def main() -> None:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")

    raw = json.loads(_INPUTS_PATH.read_text(encoding="utf-8"))
    inputs: list[dict] = raw["inputs"]

    md_lines: list[str] = []
    summary_rows: list[dict] = []

    md_lines.append("# CareCompass Walkthrough Output\n")
    md_lines.append(
        f"Generated by `scripts/run_walkthrough.py`  \n"
        f"Offline mode (no LLM).  \n"
        f"Source: `docs/user_test/walkthrough_inputs.json`\n"
    )
    md_lines.append("---\n")

    for inp in inputs:
        wid   = inp["id"]
        area  = inp["area"]
        text  = inp["text"]
        card  = inp.get("card", "?")
        style = inp.get("style", "?")
        expected_tier = inp.get("expected_tier")

        crash_msg: str | None = None
        result = None
        elapsed_ms: float = 0.0

        try:
            t0 = time.perf_counter()
            result = run_session(text, area)
            elapsed_ms = (time.perf_counter() - t0) * 1000
        except Exception as exc:  # noqa: BLE001
            crash_msg = f"CRASH: {type(exc).__name__}: {exc}"

        # ── Derive facts ──────────────────────────────────────────────────
        if result is not None:
            tier       = result.tier
            tier_icon  = _TIER_ICON.get(tier, "?")
            on_emerg   = result.state == "emergency"
            rule_hits  = (
                [f"{h.rule_id} {h.name} ({h.tier}) via {h.matched_phrase!r}"
                 for h in result.safety.hits]
                if result.safety else []
            )
            options     = _format_options(result)
            check_ok    = result.check_passed
            fc_problems = [] if check_ok else ["final_check FAILED"]
            # Handoff is offered on the present path (not emergency, not review)
            handoff_offered = (
                result.state == "present" and not result.needs_human_review
            )
            flags = _flags(inp, result)
            if crash_msg:
                flags.insert(0, crash_msg)
        else:
            tier = "—"
            tier_icon = "💥"
            on_emerg = False
            rule_hits = []
            options = []
            check_ok = False
            fc_problems = []
            handoff_offered = False
            flags = [crash_msg or "CRASH (unknown)"]

        has_flags = bool(flags)
        flag_icon = "⚠️" if has_flags else "✅"

        # ── Markdown section ──────────────────────────────────────────────
        md_lines.append(
            f"## {flag_icon} {wid} — Card {card} ({style})  "
            f"[{elapsed_ms:.0f} ms]\n"
        )
        md_lines.append(f"**Area:** {area}  ")
        md_lines.append(f"**Input:** `{text}`  ")
        md_lines.append(
            f"**Expected tier:** {expected_tier or '(none)'}  "
            f"**Actual tier:** {tier_icon} {tier}\n"
        )

        if rule_hits:
            md_lines.append("**Rule hits:**")
            for rh in rule_hits:
                md_lines.append(f"- {rh}")
            md_lines.append("")

        md_lines.append(
            f"**Emergency path taken:** {'Yes' if on_emerg else 'No'}  "
            f"**final_check passed:** {'Yes' if check_ok else 'No'}  "
            f"**Handoff offered:** {'Yes' if handoff_offered else 'No'}\n"
        )

        if options:
            md_lines.append("**Options shown:**")
            for opt in options:
                md_lines.append(opt)
            md_lines.append("")
        else:
            md_lines.append("**Options shown:** none (emergency path or no candidates)\n")

        if flags:
            md_lines.append("**⚠️ FLAGS:**")
            for f in flags:
                md_lines.append(f"- {f}")
            md_lines.append("")

        md_lines.append("---\n")

        # ── Summary row ───────────────────────────────────────────────────
        summary_rows.append({
            "id":       wid,
            "card":     card,
            "style":    style,
            "tier":     tier,
            "expected": expected_tier or "—",
            "emerg":    "Yes" if on_emerg else "No",
            "check":    "✅" if check_ok else "❌",
            "handoff":  "Yes" if handoff_offered else "No",
            "ms":       f"{elapsed_ms:.0f}",
            "flags":    "; ".join(flags) if flags else "—",
        })

    # ── Summary table in markdown ─────────────────────────────────────────
    md_lines.append("## Summary\n")
    col_w = {
        "id": 5, "card": 4, "style": 9, "tier": 9, "expected": 9,
        "emerg": 6, "check": 6, "handoff": 7, "ms": 6, "flags": 40,
    }
    headers = ["id", "card", "style", "tier", "expected",
               "emerg", "check", "handoff", "ms", "flags"]
    header_labels = {
        "id": "ID", "card": "Card", "style": "Style", "tier": "Tier",
        "expected": "Expected", "emerg": "Emerg?", "check": "Check",
        "handoff": "Handoff?", "ms": "ms", "flags": "Flags",
    }
    header_row = "| " + " | ".join(
        header_labels[h].ljust(col_w[h]) for h in headers
    ) + " |"
    sep_row = "| " + " | ".join(
        "-" * col_w[h] for h in headers
    ) + " |"
    md_lines.append(header_row)
    md_lines.append(sep_row)
    for row in summary_rows:
        md_lines.append(
            "| " + " | ".join(
                str(row[h]).ljust(col_w[h])[:col_w[h]] for h in headers
            ) + " |"
        )
    md_lines.append("")

    # ── Totals ────────────────────────────────────────────────────────────
    total = len(summary_rows)
    flagged = sum(1 for r in summary_rows if r["flags"] != "—")
    tier_mismatches = sum(
        1 for r in summary_rows
        if r["expected"] != "—" and r["tier"] != r["expected"]
    )
    crashes = sum(1 for r in summary_rows if "CRASH" in r["flags"])
    banned  = sum(1 for r in summary_rows if "BANNED" in r["flags"])

    md_lines.append(
        f"**Totals:** {total} inputs · {flagged} flagged · "
        f"{tier_mismatches} tier mismatches · {crashes} crashes · "
        f"{banned} banned-phrase hits\n"
    )

    # ── Write file ────────────────────────────────────────────────────────
    _OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    _OUTPUT_PATH.write_text("\n".join(md_lines), encoding="utf-8")
    print(f"Full output written to: {_OUTPUT_PATH}\n")

    # ── Print summary table to stdout ─────────────────────────────────────
    print("=" * 78)
    print("WALKTHROUGH SUMMARY")
    print("=" * 78)
    # Fixed-width console table
    FMT = "{:<5} {:<4} {:<9} {:<9} {:<9} {:<6} {:<6} {:<7} {:<6}  {}"
    print(FMT.format("ID", "Card", "Style", "Tier", "Expected",
                     "Emerg?", "Check", "Handoff", "ms", "Flags"))
    print("-" * 78)
    for row in summary_rows:
        print(FMT.format(
            row["id"], row["card"], row["style"], row["tier"],
            row["expected"], row["emerg"], row["check"],
            row["handoff"], row["ms"],
            row["flags"][:60] if len(row["flags"]) > 60 else row["flags"],
        ))
    print("-" * 78)
    print(
        f"Total: {total}  Flagged: {flagged}  "
        f"Tier mismatches: {tier_mismatches}  "
        f"Crashes: {crashes}  Banned-phrase hits: {banned}"
    )


if __name__ == "__main__":
    main()
